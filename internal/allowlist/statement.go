package allowlist

import (
	"fmt"
	"strings"
)

// Statement renders the published privacy statement from the allowlist.
// PRIVACY.md at the repository root is this function's output, and a test
// fails when the two differ.
//
// @spec: field-allowlist#privacy-statement-generated
// @spec: field-allowlist#statement-per-event-kind
// @spec: field-allowlist#statement-names-identity-line
func Statement() string {
	var b strings.Builder
	b.WriteString(`<!-- Generated by go run ./cmd/privacy-statement. Do not edit by hand. -->

# What the neo-tax plugin sends

The neo-tax plugin reports metadata about AI coding sessions so Neo.Tax can attribute AI token spend to the pull requests and tickets it already tracks. This page lists every field it can send. The list is generated from the allowlist inside the agent; any field not listed here is removed on the engineer's machine before it is written to disk or sent.

## Identity

The only personal identity Neo.Tax receives is the email the engineer confirms at enrollment, which is stored with the device's key rather than sent with each event, plus the repository-level git ` + "`user.email`" + ` on ` + "`session.opened`" + ` as a signal for joining sessions to pull-request authors.

## Never sent

Prompt text, completion text, tool inputs, tool outputs, file paths, the working-directory path, and session titles never leave the machine.

## Fields by event kind
`)
	for _, kind := range Kinds() {
		fields, _ := For(kind)
		fmt.Fprintf(&b, "\n### `%s`\n\n| Field | Contents |\n| --- | --- |\n", kind)
		writeRows(&b, "", fields)
	}
	return b.String()
}

// writeRows writes one table row per field, then recurses into its Children
// under the field's dotted name, so the statement lists every field Apply
// lets through at any depth.
//
// @spec: field-allowlist#statement-per-event-kind
func writeRows(b *strings.Builder, prefix string, fields []Field) {
	for _, f := range fields {
		fmt.Fprintf(b, "| `%s%s` | %s |\n", prefix, f.Name, f.Description)
		writeRows(b, prefix+f.Name+".", f.Children)
	}
}
