package allowlist

import (
	"fmt"
	"strings"
)

// Statement renders the published privacy statement from the allowlist.
// PRIVACY.md at the repository root is this function's output, and a test
// fails when the two differ.
//
// @spec: field-allowlist#privacy-statement-generated
// @spec: field-allowlist#statement-per-event-kind
// @spec: field-allowlist#statement-names-identity-line
// @spec: field-allowlist#statement-names-incidental-identity
// @spec: field-allowlist#statement-covers-enrollment
// @spec: claude-code-telemetry-export#privacy-statement-covers-telemetry
func Statement() string {
	var b strings.Builder
	b.WriteString(`<!-- Generated by go run ./cmd/privacy-statement. Do not edit by hand. -->

# What the neo-tax plugin sends

The neo-tax plugin reports metadata about AI coding sessions so Neo.Tax can attribute AI token spend to the pull requests and tickets it already tracks. This page lists every field it can send. The list is generated from the allowlist inside the agent; any field not listed here is removed on the engineer's machine before it is written to disk or sent. When an organization also turns on Claude Code's own telemetry, Claude Code sends it to Neo.Tax separately; the last section lists what Neo.Tax keeps of it.

## Identity

From the plugin, Neo.Tax receives one value meant to identify the engineer: the email the engineer confirms at enrollment, which is stored with the device's key rather than sent with each event. Events carry the device id, and Neo.Tax knows which engineer enrolled the device.

Three other values are not meant to identify anyone but can. ` + "`branch`" + ` is free text the engineer or their tools choose, so it can contain a name, a username, or anything else typed into it. ` + "`repo.owner`" + ` is the account that owns the repository, which is a personal username when the repository lives under a personal account rather than an organization. The device hostname, sent once at enrollment as a readable name for the device, often contains the engineer's name.

Claude Code's own telemetry, when an organization turns it on, also carries the email of the engineer's Claude account, which is meant to identify the engineer, and ` + "`vcs.owner.name`" + `, which is a personal username in the same case as ` + "`repo.owner`" + `; see the last section.

## Never sent

Prompt text, completion text, tool inputs, tool outputs, file paths, the working-directory path, and session titles never leave the machine.

## Fields by event kind
`)
	for _, kind := range Kinds() {
		fields, _ := For(kind)
		fmt.Fprintf(&b, "\n### `%s`\n\n| Field | Contents |\n| --- | --- |\n", kind)
		writeRows(&b, "", fields)
	}
	b.WriteString(enrollmentSection())
	b.WriteString(telemetrySection())
	return b.String()
}

// writeRows writes one table row per field, then recurses into its Children
// under the field's dotted name (suffixed [] for a list), so the statement lists every field Apply
// lets through at any depth.
//
// @spec: field-allowlist#statement-per-event-kind
func writeRows(b *strings.Builder, prefix string, fields []Field) {
	for _, f := range fields {
		fmt.Fprintf(b, "| `%s%s` | %s |\n", prefix, f.Name, f.Description)
		parent := prefix + f.Name
		if f.List {
			parent += "[]"
		}
		writeRows(b, parent+".", f.Children)
	}
}
